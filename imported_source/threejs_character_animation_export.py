def _export_glb(filepath, objects, *, animations, frame_step=1):
    bpy.ops.object.mode_set(mode="OBJECT") if bpy.context.object and \
        bpy.context.object.mode != "OBJECT" else None
    bpy.ops.object.select_all(action="DESELECT")
    for obj in objects:
        obj.hide_set(False)
        obj.hide_viewport = False
        obj.select_set(True)
    bpy.context.view_layer.objects.active = objects[0]

    image_format = (
        TEXTURE_IMAGE_FORMAT
        if EXPORT_MATERIALS and EXPORT_TEXTURES
        else "NONE"
    )
    use_draco = MESH_COMPRESSION == "DRACO" and not animations
    options = dict(
        filepath=filepath,
        export_format="GLB",
        use_selection=True,
        export_yup=True,
        export_apply=False,
        export_materials="EXPORT" if EXPORT_MATERIALS else "NONE",
        export_image_format=image_format,
        export_jpeg_quality=TEXTURE_QUALITY,
        export_image_quality=TEXTURE_QUALITY,
        export_vertex_color="MATERIAL" if EXPORT_VERTEX_COLORS else "NONE",
        export_all_vertex_colors=EXPORT_VERTEX_COLORS,
        export_tangents=EXPORT_TANGENTS,
        export_extras=EXPORT_CUSTOM_PROPERTIES,
        export_draco_mesh_compression_enable=use_draco,
        export_draco_mesh_compression_level=DRACO_COMPRESSION_LEVEL,
        export_draco_position_quantization=DRACO_POSITION_QUANTIZATION,
        export_draco_normal_quantization=DRACO_NORMAL_QUANTIZATION,
        export_draco_texcoord_quantization=DRACO_TEXCOORD_QUANTIZATION,
        export_draco_color_quantization=DRACO_COLOR_QUANTIZATION,
        export_draco_generic_quantization=DRACO_GENERIC_QUANTIZATION,
        export_skins=True,
        export_def_bones=False,
        export_rest_position_armature=True,
        export_leaf_bone=False,
        export_morph=EXPORT_MORPH_TARGETS,
        export_animations=animations,
    )
    if animations:
        options.update(
            export_animation_mode="ACTIONS",
            export_merge_animation="ACTION",
            export_force_sampling=SAMPLE_BAKED_ANIMATION,
            export_frame_step=frame_step,
            export_optimize_animation_size=True,
            export_optimize_animation_keep_anim_armature=True,
            export_anim_single_armature=True,
            export_anim_slide_to_zero=True,
            export_morph_animation=EXPORT_MORPH_TARGETS,
            export_extra_animations=False,
        )
    else:
        options.update(export_morph_animation=False)

    result = bpy.ops.export_scene.gltf(**options)
    if "FINISHED" not in result:
        raise RuntimeError(f"Blender cancelled GLB export: {filepath}")


def _read_glb(filepath):
    with open(filepath, "rb") as handle:
        header = handle.read(12)
        if len(header) != 12:
            raise ValueError(f"Invalid GLB header: {filepath}")
        magic, version, total_length = struct.unpack("<4sII", header)
        if magic != b"glTF" or version != 2:
            raise ValueError(f"Not a glTF 2.0 GLB: {filepath}")

        document = None
        binary = b""
        while handle.tell() < total_length:
            chunk_header = handle.read(8)
            if len(chunk_header) != 8:
                raise ValueError("Truncated GLB chunk header.")
            chunk_length, chunk_type = struct.unpack("<II", chunk_header)
            chunk = handle.read(chunk_length)
            if len(chunk) != chunk_length:
                raise ValueError("Truncated GLB chunk.")
            if chunk_type == 0x4E4F534A:
                document = json.loads(
                    chunk.rstrip(b"\x00 \t\r\n").decode("utf-8")
                )
            elif chunk_type == 0x004E4942:
                binary = chunk

    if document is None:
        raise ValueError("GLB contains no JSON document.")
    return document, binary


def _normalize_component(value, component_type):
    if component_type == 5120:
        return max(value / 127.0, -1.0)
    if component_type == 5121:
        return value / 255.0
    if component_type == 5122:
        return max(value / 32767.0, -1.0)
    if component_type == 5123:
        return value / 65535.0
    return value


def _read_accessor(document, binary, accessor_index):
    accessor = document["accessors"][accessor_index]
    width = _ACCESSOR_WIDTHS[accessor["type"]]
    count = accessor["count"]
    component_type = accessor["componentType"]
    component_format = _COMPONENT_FORMATS[component_type]
    component_size = struct.calcsize("<" + component_format)
    element_size = component_size * width

    if "bufferView" not in accessor:
        return [[0.0] * width for _ in range(count)]

    view = document["bufferViews"][accessor["bufferView"]]
    offset = view.get("byteOffset", 0) + accessor.get("byteOffset", 0)
    stride = view.get("byteStride", element_size)
    unpack_format = "<" + component_format * width
    normalized = accessor.get("normalized", False)
    values = []

    for index in range(count):
        item = list(struct.unpack_from(
            unpack_format, binary, offset + index * stride
        ))
        if normalized:
            item = [
                _normalize_component(value, component_type)
                for value in item
            ]
        values.append(item)
    return values


