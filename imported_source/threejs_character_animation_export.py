def _safe_identifier(name):
    identifier = re.sub(r"\W+", "_", name, flags=re.UNICODE).strip("_")
    if not identifier:
        identifier = "Animation"
    if identifier[0].isdigit() or identifier in _TS_RESERVED:
        identifier = f"Animation_{identifier}"
    return identifier


def _safe_filename(name):
    filename = re.sub(r'[<>:"/\\|?*\x00-\x1F]+', "_", name).strip(" .")
    if not filename:
        filename = "Animation"
    if filename.upper() in _WINDOWS_RESERVED:
        filename = f"Animation_{filename}"
    return filename


def _unique_names(animations):
    used_identifiers = set()
    used_files = set()
    result = []
    for animation in animations:
        base_identifier = _safe_identifier(animation["name"])
        base_file = _safe_filename(animation["name"])
        identifier = base_identifier
        filename = base_file
        suffix = 2
        while (identifier.casefold() in used_identifiers or
               filename.casefold() in used_files):
            identifier = f"{base_identifier}_{suffix}"
            filename = f"{base_file}_{suffix}"
            suffix += 1
        used_identifiers.add(identifier.casefold())
        used_files.add(filename.casefold())
        result.append((animation, identifier, filename))
    return result


def _atomic_write(filepath, content):
    temporary = filepath + ".tmp"
    with open(temporary, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(content)
    os.replace(temporary, filepath)


def _remove_old_generated_animation_files(animation_dir):
    if not os.path.isdir(animation_dir):
        return
    for filename in os.listdir(animation_dir):
        if not filename.endswith(".ts"):
            continue
        filepath = os.path.join(animation_dir, filename)
        try:
            with open(filepath, "r", encoding="utf-8") as handle:
                first_line = handle.readline().rstrip("\r\n")
            if first_line == _GENERATED_MARKER:
                os.remove(filepath)
        except OSError:
            continue


def _animation_module(animation, identifier):
    compact = json.dumps(
        animation, ensure_ascii=False, separators=(",", ":"), allow_nan=False
    )
    return (
        f"{_GENERATED_MARKER}\n"
        'import type { AnimationData } from "../animationClipFactory";\n\n'
        f"export const {identifier} = {compact} as const "
        "satisfies AnimationData;\n"
        f"export default {identifier};\n"
    )


def _index_module(named_animations):
    imports = "\n".join(
        f'import {{ {identifier} }} from "./{filename}";'
        for _animation, identifier, filename in named_animations
    )
    exports = ", ".join(
        identifier for _animation, identifier, _filename in named_animations
    )
    return (
        f"{_GENERATED_MARKER}\n"
        f"{imports}\n\n"
        f"export {{ {exports} }};\n"
        f"export const animations = [{exports}] as const;\n"
    )


def _factory_module():
    return f"""{_GENERATED_MARKER}
import * as THREE from "three";

export type AnimationProperty =
  | "position"
  | "quaternion"
  | "scale"
  | `morphTargetInfluences[${{number}}]`;

export interface AnimationTrackData {{
  readonly target: string;
  readonly property: AnimationProperty;
  readonly times: readonly number[];
  readonly values: readonly number[];
  readonly interpolation?: "linear" | "discrete";
  readonly morphTarget?: string;
}}

export interface AnimationData {{
  readonly name: string;
  readonly duration: number;
  readonly fps: number;
  readonly tracks: readonly AnimationTrackData[];
}}

function createTrack(track: AnimationTrackData): THREE.KeyframeTrack {{
  const binding = `${{track.target}}.${{track.property}}`;
  const times = Array.from(track.times);
  const values = Array.from(track.values);
  let result: THREE.KeyframeTrack;

  if (track.property === "quaternion") {{
    result = new THREE.QuaternionKeyframeTrack(binding, times, values);
  }} else if (
    track.property === "position" ||
    track.property === "scale"
  ) {{
    result = new THREE.VectorKeyframeTrack(binding, times, values);
  }} else {{
    result = new THREE.NumberKeyframeTrack(binding, times, values);
  }}

  if (track.interpolation === "discrete") {{
    result.setInterpolation(THREE.InterpolateDiscrete);
  }}
  return result;
}}

export function createAnimationClip(
  animation: AnimationData,
): THREE.AnimationClip {{
  const tracks = animation.tracks.map(createTrack);
  return new THREE.AnimationClip(animation.name, animation.duration, tracks);
}}

export function createAnimationClips(
  animations: readonly AnimationData[],
): THREE.AnimationClip[] {{
  return animations.map(createAnimationClip);
}}
"""


