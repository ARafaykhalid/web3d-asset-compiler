def _human_size(byte_count):
    size = float(byte_count)
    for unit in ("B", "KB", "MB", "GB"):
        if size < 1024.0 or unit == "GB":
            return f"{size:.1f} {unit}"
        size /= 1024.0


def _snapshot_scene_state(objects):
    return {
        "active": (bpy.context.view_layer.objects.active.name
                   if bpy.context.view_layer.objects.active else None),
        "selected": [obj.name for obj in bpy.context.selected_objects],
        "hidden": {
            obj.name: (obj.hide_get(), obj.hide_viewport)
            for obj in objects
        },
        "frame": bpy.context.scene.frame_current,
    }


def _restore_scene_state(state):
    for name, (hidden, hide_viewport) in state["hidden"].items():
        obj = bpy.data.objects.get(name)
        if obj:
            obj.hide_set(hidden)
            obj.hide_viewport = hide_viewport
    try:
        bpy.ops.object.select_all(action="DESELECT")
    except Exception:
        pass
    for name in state["selected"]:
        obj = bpy.data.objects.get(name)
        if obj and not obj.hide_get() and not obj.hide_viewport:
            obj.select_set(True)
    active = bpy.data.objects.get(state["active"]) if state["active"] else None
    if active:
        bpy.context.view_layer.objects.active = active
    bpy.context.scene.frame_set(state["frame"])


def export_character_and_animations():
    if not GLB_FILENAME.lower().endswith(".glb"):
        raise ValueError("GLB_FILENAME must end with '.glb'.")
    if os.path.basename(GLB_FILENAME) != GLB_FILENAME:
        raise ValueError("GLB_FILENAME must be a filename, not a path.")
    if OUTPUT_DIRECTORY.startswith("//") and not bpy.data.filepath:
        raise RuntimeError(
            "Save the .blend file first or configure an absolute "
            "OUTPUT_DIRECTORY."
        )
    if DECIMAL_PRECISION < 3 or DECIMAL_PRECISION > 9:
        raise ValueError("DECIMAL_PRECISION must be between 3 and 9.")
    if SAMPLING_FPS <= 0:
        raise ValueError("SAMPLING_FPS must be greater than zero.")

    output_dir = bpy.path.abspath(OUTPUT_DIRECTORY)
    animation_dir = os.path.join(output_dir, "animations")
    glb_path = os.path.join(output_dir, GLB_FILENAME)
    staging_path = os.path.join(output_dir, _STAGING_FILENAME)
    factory_path = os.path.join(output_dir, "animationClipFactory.ts")
    index_path = os.path.join(animation_dir, "index.ts")

    armature, meshes = _find_primary_armature()
    character_objects = _collect_character_objects(armature, meshes)
    actions = _find_character_actions(armature, meshes)
    wanted_names = {action.name for action in actions}

    scene_fps = (
        bpy.context.scene.render.fps /
        bpy.context.scene.render.fps_base
    )
    frame_step = max(1, int(round(scene_fps / SAMPLING_FPS)))
    effective_fps = scene_fps / frame_step

    os.makedirs(animation_dir, exist_ok=True)
    state = _snapshot_scene_state(character_objects)
    quarantine = None
    quarantine_records = []
    generated_files = []

    try:
        print(f"[Three.js Export] Primary Armature: {armature.name}")
        print(
            f"[Three.js Export] Skinned meshes: "
            f"{', '.join(mesh.name for mesh in meshes)}"
        )

        _export_glb(glb_path, character_objects, animations=False)
        character_document, _character_binary = _read_glb(glb_path)
        if character_document.get("animations"):
            raise RuntimeError("character.glb unexpectedly contains animations.")
        if not character_document.get("skins"):
            raise RuntimeError(
                "character.glb contains no skin. Check the Armature modifiers "
                "and vertex groups on the detected meshes."
            )
        generated_files.append(glb_path)

        animation_data = []
        if actions:
            quarantine, quarantine_records = _quarantine_unsafe_fcurves()
            if quarantine_records:
                print(
                    f"[Three.js Export] Temporarily skipped "
                    f"{len(quarantine_records)} unsupported F-curve(s)."
                )
                for _collection, _copy, action_name, path, index in \
                        quarantine_records[:10]:
                    print(
                        f"  - {action_name}: {path}[{index}]"
                    )

            _export_glb(
                staging_path, character_objects,
                animations=True, frame_step=frame_step,
            )
            animation_document, animation_binary = _read_glb(staging_path)
            animation_data = _extract_animation_data(
                animation_document, animation_binary,
                wanted_names, effective_fps,
            )

        exported_names = {animation["name"] for animation in animation_data}
        missing = sorted(wanted_names - exported_names, key=str.casefold)
        if missing:
            raise RuntimeError(
                "Blender did not emit these character Actions: "
                + ", ".join(missing)
            )

        _remove_old_generated_animation_files(animation_dir)
        named_animations = _unique_names(animation_data)
        for animation, identifier, filename in named_animations:
            filepath = os.path.join(animation_dir, filename + ".ts")
            _atomic_write(filepath, _animation_module(animation, identifier))
            generated_files.append(filepath)

        _atomic_write(index_path, _index_module(named_animations))
        _atomic_write(factory_path, _factory_module())
        generated_files.extend([index_path, factory_path])

        track_count = sum(
            len(animation["tracks"]) for animation in animation_data
        )
        keyframe_count = sum(
            len(track["times"])
            for animation in animation_data
            for track in animation["tracks"]
        )

        print("\n" + "=" * 72)
        print("THREE.JS CHARACTER EXPORT COMPLETE")
        print("=" * 72)
        print(f"Character GLB: {glb_path}")
        print(f"Armature: {armature.name}")
        print(f"Animations: {len(animation_data)}")
        for animation in animation_data:
            keys = sum(len(track["times"]) for track in animation["tracks"])
            print(
                f"  - {animation['name']}: "
                f"{len(animation['tracks'])} tracks, {keys} keyframes, "
                f"{animation['duration']}s"
            )
        print(f"Total tracks: {track_count}")
        print(f"Total keyframes: {keyframe_count}")
        print(f"Sampling FPS: {effective_fps:g} (frame step {frame_step})")
        print("Generated files:")
        for filepath in generated_files:
            print(
                f"  {filepath} — {_human_size(os.path.getsize(filepath))}"
            )
        print("=" * 72)

        return {
            "character_glb": glb_path,
            "animations": animation_data,
            "tracks": track_count,
            "keyframes": keyframe_count,
            "files": generated_files,
        }
    finally:
        if quarantine:
            try:
                _restore_quarantined_fcurves(
                    quarantine, quarantine_records
                )
            except Exception:
                print(
                    "[Three.js Export] ERROR restoring quarantined F-curves. "
                    "They remain preserved in __TJS_EXPORT_QUARANTINE__."
                )
                traceback.print_exc()
        if os.path.isfile(staging_path):
            try:
                os.remove(staging_path)
            except OSError:
                pass
        _restore_scene_state(state)


if __name__ == "__main__":
    try:
        export_character_and_animations()
    except Exception:
        print("[Three.js Export] FAILED")
        traceback.print_exc()
        raise
