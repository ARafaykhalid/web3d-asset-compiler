def _skinned_meshes_for_armature(armature):
    meshes = []
    for obj in bpy.context.scene.objects:
        if obj.type != "MESH":
            continue
        uses_armature = any(
            modifier.type == "ARMATURE" and modifier.object == armature
            for modifier in obj.modifiers
        )
        parented_to_armature = (
            obj.parent == armature and obj.parent_type in {"ARMATURE", "BONE"}
        )
        if uses_armature or parented_to_armature:
            meshes.append(obj)
    return sorted(meshes, key=lambda obj: obj.name)


def _find_primary_armature():
    candidates = []
    for armature in (obj for obj in bpy.context.scene.objects
                     if obj.type == "ARMATURE"):
        meshes = _skinned_meshes_for_armature(armature)
        vertex_count = sum(len(mesh.data.vertices) for mesh in meshes)
        candidates.append((len(meshes), vertex_count, armature.name,
                           armature, meshes))

    if not candidates:
        raise RuntimeError("No Armature exists in the current scene.")

    candidates.sort(key=lambda item: (item[0], item[1], item[2]), reverse=True)
    mesh_count, _vertices, _name, armature, meshes = candidates[0]
    if mesh_count == 0:
        raise RuntimeError(
            f"Found Armature '{armature.name}', but no meshes are skinned to it."
        )
    return armature, meshes


def _collect_character_objects(armature, meshes):
    result = {armature, *meshes}
    pending = list(result)
    while pending:
        obj = pending.pop()
        if obj.parent and obj.parent not in result:
            result.add(obj.parent)
            pending.append(obj.parent)
    return sorted(result, key=lambda obj: obj.name)


def _iter_action_fcurve_collections(action):
    found_slotted = False
    for layer in getattr(action, "layers", []):
        for strip in layer.strips:
            for channelbag in getattr(strip, "channelbags", []):
                found_slotted = True
                yield channelbag.fcurves
    if found_slotted:
        return
    try:
        yield action.fcurves
    except (AttributeError, RuntimeError):
        pass


def _iter_action_fcurves(action):
    for collection in _iter_action_fcurve_collections(action):
        yield from collection


def _action_has_keyframes(action):
    return any(
        len(fcurve.keyframe_points) > 0 or len(fcurve.sampled_points) > 0
        for fcurve in _iter_action_fcurves(action)
    )


def _actions_used_by_id(data_block):
    result = set()
    animation_data = getattr(data_block, "animation_data", None)
    if not animation_data:
        return result
    if animation_data.action:
        result.add(animation_data.action)
    for track in animation_data.nla_tracks:
        for strip in track.strips:
            if strip.action:
                result.add(strip.action)
    return result


def _find_character_actions(armature, meshes):
    used = _actions_used_by_id(armature)
    shape_key_names = set()
    for mesh in meshes:
        used.update(_actions_used_by_id(mesh))
        shape_keys = mesh.data.shape_keys
        if shape_keys and EXPORT_MORPH_TARGETS:
            used.update(_actions_used_by_id(shape_keys))
            shape_key_names.update(key.name for key in shape_keys.key_blocks)

    actions = set(used)
    if EXPORT_ALL_ACTIONS:
        bone_names = set(armature.data.bones.keys())
        bone_pattern = re.compile(r'pose\.bones\["((?:\\.|[^"])*)"\]')
        shape_pattern = re.compile(r'key_blocks\["((?:\\.|[^"])*)"\]\.value')
        for action in bpy.data.actions:
            for fcurve in _iter_action_fcurves(action):
                bone_match = bone_pattern.search(fcurve.data_path)
                if bone_match and bone_match.group(1) in bone_names:
                    actions.add(action)
                    break
                shape_match = shape_pattern.search(fcurve.data_path)
                if shape_match and shape_match.group(1) in shape_key_names:
                    actions.add(action)
                    break

    excluded = {name.casefold() for name in ACTIONS_TO_EXCLUDE}
    return sorted(
        (action for action in actions
         if action.name.casefold() not in excluded
         and _action_has_keyframes(action)),
        key=lambda action: action.name.casefold(),
    )


