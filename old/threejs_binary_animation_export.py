def _extract_raw_standard_track(document, binary, channel, sampler, node_names):
    node_index = channel["target"]["node"]
    path = channel["target"]["path"]
    times = [row[0] for row in _read_accessor(document, binary, sampler["input"])]
    values = _read_accessor(document, binary, sampler["output"])
    interpolation = sampler.get("interpolation", "LINEAR")
    if interpolation == "CUBICSPLINE":
        values = _take_cubic_spline_values(values)
        interpolation = "LINEAR"
    property_name = {"translation": "position", "rotation": "quaternion", "scale": "scale"}[path]
    return {
        "target": node_names[node_index], "property": property_name, "morph_index": 0xFFFF,
        "interpolation": interpolation, "times": [float(value) for value in times],
        "values": [[float(component) for component in row] for row in values],
        "rest": [float(value) for value in _node_rest_value(document, node_index, path)],
    }


def _extract_raw_weight_tracks(document, binary, channel, sampler, node_names):
    node_index = channel["target"]["node"]
    node = document["nodes"][node_index]
    mesh = document["meshes"][node["mesh"]]
    times = [row[0] for row in _read_accessor(document, binary, sampler["input"])]
    rows = _read_accessor(document, binary, sampler["output"])
    flat = [component for row in rows for component in row]
    interpolation = sampler.get("interpolation", "LINEAR")
    divisor = len(times) * (3 if interpolation == "CUBICSPLINE" else 1)
    target_count = len(flat) // divisor if divisor else 0
    if target_count == 0:
        return []
    if interpolation == "CUBICSPLINE":
        sampled = []
        block = target_count * 3
        for index in range(len(times)):
            start = index * block + target_count
            sampled.append(flat[start:start + target_count])
        interpolation = "LINEAR"
    else:
        sampled = [flat[index * target_count:(index + 1) * target_count] for index in range(len(times))]
    rest_weights = node.get("weights", mesh.get("weights", [0.0] * target_count))
    return [{
        "target": node_names[node_index], "property": "morph", "morph_index": target_index,
        "interpolation": interpolation, "times": [float(value) for value in times],
        "values": [[float(row[target_index])] for row in sampled],
        "rest": [float(rest_weights[target_index] if target_index < len(rest_weights) else 0.0)],
    } for target_index in range(target_count)]


def _extract_raw_animation_data(document, binary, wanted_names, effective_fps):
    grouped = {}
    node_names = _three_node_names(document)
    for animation_index, animation in enumerate(document.get("animations", [])):
        name = animation.get("name") or f"Animation_{animation_index + 1}"
        if name not in wanted_names:
            continue
        entry = grouped.setdefault(name, {"name": name, "tracks": [], "duration": 0.0})
        for channel in animation.get("channels", []):
            sampler = animation["samplers"][channel["sampler"]]
            path = channel.get("target", {}).get("path")
            if path in {"translation", "rotation", "scale"}:
                entry["tracks"].append(_extract_raw_standard_track(document, binary, channel, sampler, node_names))
            elif path == "weights":
                entry["tracks"].extend(_extract_raw_weight_tracks(document, binary, channel, sampler, node_names))
        entry["duration"] = max((max(track["times"]) for track in entry["tracks"] if track["times"]), default=0.0)
        entry["fps"] = float(effective_fps)
    return [grouped[name] for name in sorted(grouped, key=str.casefold)]


def _exact_sample_times(duration, fps):
    """Return a requested-FPS time grid while always preserving the endpoint."""
    duration = max(0.0, float(duration))
    fps = float(fps)
    if duration <= 1e-12:
        return [0.0]

    whole_steps = int(math.floor(duration * fps + 1e-9))
    times = [index / fps for index in range(whole_steps + 1)]
    endpoint_epsilon = max(1e-7, 1.0 / fps * 1e-6)
    if abs(times[-1] - duration) <= endpoint_epsilon:
        times[-1] = duration
    elif times[-1] < duration:
        times.append(duration)
    return times


def _resample_raw_animations(animations, fps):
    """Resample evaluated glTF-space tracks at the exact requested rate."""
    requested_fps = float(fps)
    result = []
    for animation in animations:
        duration = float(animation.get("duration", 0.0))
        sample_times = _exact_sample_times(duration, requested_fps)
        tracks = []
        for track in animation["tracks"]:
            source_times = track["times"]
            source_values = track["values"]
            if not source_times or len(source_times) != len(source_values):
                continue
            sampled_values = [
                list(_sample_values(
                    source_times,
                    source_values,
                    target_time,
                    track["property"],
                    track.get("interpolation", "LINEAR"),
                ))
                for target_time in sample_times
            ]
            tracks.append({
                **track,
                "times": list(sample_times),
                "values": sampled_values,
            })
        result.append({
            **animation,
            "duration": duration,
            "fps": requested_fps,
            "tracks": tracks,
        })
    return result


def _track_tolerance(property_name):
    if property_name == "position":
        return POSITION_TOLERANCE
    if property_name == "quaternion":
        return math.radians(ROTATION_TOLERANCE_DEGREES)
    if property_name == "scale":
        return SCALE_TOLERANCE
    return MORPH_TOLERANCE


def _property_error(property_name, first, second):
    if property_name == "quaternion":
        a = _quat_normalize(first)
        b = _quat_normalize(second)
        dot = min(1.0, max(-1.0, abs(sum(x * y for x, y in zip(a, b)))))
        return 2.0 * math.acos(dot)
    if property_name == "position":
        return math.sqrt(sum((a - b) ** 2 for a, b in zip(first, second)))
    return max((abs(a - b) for a, b in zip(first, second)), default=0.0)


def _sample_values(times, values, target_time, property_name, interpolation="LINEAR"):
    if len(times) == 1 or target_time <= times[0]:
        return values[0]
    if target_time >= times[-1]:
        return values[-1]
    low, high = 0, len(times) - 1
    while low + 1 < high:
        middle = (low + high) // 2
        if times[middle] <= target_time:
            low = middle
        else:
            high = middle
    if interpolation == "STEP":
        return values[low]
    span = times[high] - times[low]
    factor = 0.0 if abs(span) <= 1e-12 else (target_time - times[low]) / span
    return _interpolated_value(values[low], values[high], factor, property_name)


def _reduce_linear_indices(times, values, property_name, tolerance):
    keep = {0, len(times) - 1}
    stack = [(0, len(times) - 1)]
    while stack:
        start, end = stack.pop()
        if end <= start + 1:
            continue
        span = times[end] - times[start]
        worst_error, worst_index = -1.0, None
        for index in range(start + 1, end):
            factor = 0.0 if abs(span) <= 1e-12 else (times[index] - times[start]) / span
            predicted = _interpolated_value(values[start], values[end], factor, property_name)
            error = _property_error(property_name, values[index], predicted)
            if error > worst_error:
                worst_error, worst_index = error, index
        if worst_index is not None and worst_error > tolerance:
            keep.add(worst_index)
            stack.append((start, worst_index))
            stack.append((worst_index, end))
    return sorted(keep)


def _optimize_binary_track(raw_track):
    times = raw_track["times"]
    original_values = raw_track["values"]
    if not times or len(times) != len(original_values):
        return None
    property_name = raw_track["property"]
    tolerance = _track_tolerance(property_name)
    values = []
    for value in original_values:
        rounded = [round(float(component), DECIMAL_PRECISION) for component in value]
        if property_name == "quaternion":
            rounded = _quat_normalize(rounded)
            if values and sum(a * b for a, b in zip(values[-1], rounded)) < 0.0:
                rounded = [-component for component in rounded]
        values.append(rounded)
    is_constant = all(_property_error(property_name, values[0], value) <= tolerance for value in values[1:])
    if is_constant:
        matches_rest = raw_track["rest"] is not None and all(
            _property_error(property_name, value, raw_track["rest"]) <= tolerance for value in values
        )
        if REMOVE_STATIC_TRACKS and matches_rest:
            return None
        indices = [0]
    elif raw_track["interpolation"] == "STEP":
        indices = [0]
        for index in range(1, len(times)):
            if _property_error(property_name, values[index - 1], values[index]) > tolerance:
                indices.append(index)
        if indices[-1] != len(times) - 1:
            indices.append(len(times) - 1)
    elif ENABLE_KEYFRAME_REDUCTION and len(times) > 2:
        indices = _reduce_linear_indices(times, values, property_name, tolerance * 0.9)
    else:
        indices = list(range(len(times)))
    return {
        **{key: raw_track[key] for key in ("target", "property", "morph_index", "interpolation")},
        "times": [times[index] for index in indices],
        "values": [values[index] for index in indices],
        "original_times": times, "original_values": original_values,
    }


def _quantization_allowed(property_name):
    return ENABLE_QUANTIZATION and (
        (property_name == "quaternion" and QUANTIZE_QUATERNIONS) or
        (property_name == "position" and QUANTIZE_POSITIONS) or
        (property_name == "scale" and QUANTIZE_SCALES) or
        (property_name == "morph" and QUANTIZE_MORPHS)
    )


def _choose_value_encoding(track):
    values = track["values"]
    property_name = track["property"]
    tolerance = _track_tolerance(property_name)
    if not _quantization_allowed(property_name):
        return _ENCODING_FLOAT32, None, values
    if property_name == "quaternion":
        encoded, decoded = [], []
        for value in values:
            row = [max(-32767, min(32767, int(round(component * 32767.0)))) for component in value]
            encoded.append(row)
            decoded.append(_quat_normalize([component / 32767.0 for component in row]))
        error = max((_property_error(property_name, source, rebuilt) for source, rebuilt in zip(values, decoded)), default=0.0)
        if error <= tolerance:
            return _ENCODING_QUAT_INT16, encoded, decoded
        return _ENCODING_FLOAT32, None, values
    width = len(values[0])
    minimum = [min(row[index] for row in values) for index in range(width)]
    maximum = [max(row[index] for row in values) for index in range(width)]
    encoded, decoded = [], []
    for value in values:
        encoded_row, decoded_row = [], []
        for index, component in enumerate(value):
            span = maximum[index] - minimum[index]
            quantized = 0 if abs(span) <= 1e-20 else int(round((component - minimum[index]) * 65535.0 / span))
            quantized = max(0, min(65535, quantized))
            encoded_row.append(quantized)
            decoded_row.append(minimum[index] if abs(span) <= 1e-20 else minimum[index] + (quantized / 65535.0) * span)
        encoded.append(encoded_row)
        decoded.append(decoded_row)
    error = max((_property_error(property_name, source, rebuilt) for source, rebuilt in zip(values, decoded)), default=0.0)
    if error <= tolerance:
        encoding = _ENCODING_SCALAR_UINT16 if width == 1 else _ENCODING_VECTOR_UINT16
        return encoding, {"minimum": minimum, "maximum": maximum, "values": encoded}, decoded
    return _ENCODING_FLOAT32, None, values


def _choose_time_encoding(times, fps):
    sample_indices = [int(round(value * fps)) for value in times]
    on_grid = all(abs(value - index / fps) <= 1e-5 for value, index in zip(times, sample_indices))
    if on_grid:
        if len(sample_indices) <= 1:
            return _TIME_UNIFORM, (sample_indices[0] if sample_indices else 0, 0)
        step = sample_indices[1] - sample_indices[0]
        if all(sample_indices[index] - sample_indices[index - 1] == step for index in range(2, len(sample_indices))):
            return _TIME_UNIFORM, (sample_indices[0], step)
        if min(sample_indices) >= 0 and max(sample_indices) <= 0xFFFF:
            return _TIME_UINT16, sample_indices
        if min(sample_indices) >= 0:
            return _TIME_UINT32, sample_indices
    return _TIME_FLOAT32, times


def _validate_optimized_track(track, decoded_values):
    maximum = 0.0
    for time_value, source in zip(track["original_times"], track["original_values"]):
        rebuilt = _sample_values(track["times"], decoded_values, time_value, track["property"], track["interpolation"])
        maximum = max(maximum, _property_error(track["property"], source, rebuilt))
    return maximum


def _align(data, alignment=4):
    padding = (-len(data)) % alignment
    if padding:
        data.extend(b"\0" * padding)


def _append_values(data, fmt, rows):
    packer = struct.Struct("<" + fmt)
    for row in rows:
        for value in row:
            data.extend(packer.pack(value))


def _write_binary_animation(filepath, animation, target_ids, mapping_hash):
    data = bytearray(b"\0" * _HEADER_SIZE)
    total_keys = 0
    contains_quantization = False
    validation = dict(animation.get("removed_validation", {"position": 0.0, "quaternion": 0.0, "scale": 0.0, "morph": 0.0}))
    for track in animation["tracks"]:
        target_id = target_ids[track["target"]]
        encoding, encoded, decoded_values = _choose_value_encoding(track)
        time_mode, time_payload = _choose_time_encoding(track["times"], animation["fps"])
        validation[track["property"]] = max(validation[track["property"]], _validate_optimized_track(track, decoded_values))
        key_count = len(track["times"])
        component_count = len(track["values"][0])
        total_keys += key_count
        contains_quantization = contains_quantization or encoding != _ENCODING_FLOAT32
        data.extend(struct.pack("<HBBBBBBHHI", target_id, _PROPERTY_CODES[track["property"]],
            _INTERPOLATION_CODES.get(track["interpolation"], 0), encoding, time_mode,
            component_count, 0, track["morph_index"], 0, key_count))
        if time_mode == _TIME_UNIFORM:
            data.extend(struct.pack("<II", time_payload[0], time_payload[1]))
        elif time_mode == _TIME_UINT16:
            data.extend(struct.pack("<" + "H" * key_count, *time_payload))
        elif time_mode == _TIME_UINT32:
            data.extend(struct.pack("<" + "I" * key_count, *time_payload))
        else:
            data.extend(struct.pack("<" + "f" * key_count, *time_payload))
        _align(data)
        if encoding == _ENCODING_FLOAT32:
            _append_values(data, "f", track["values"])
        elif encoding == _ENCODING_QUAT_INT16:
            _append_values(data, "h", encoded)
        else:
            _append_values(data, "f", [encoded["minimum"], encoded["maximum"]])
            _append_values(data, "H", encoded["values"])
        _align(data)
    flags = 1 if contains_quantization else 0
    struct.pack_into("<4sHHffHHIII", data, 0, _MAGIC, _FORMAT_VERSION, _HEADER_SIZE,
        float(animation["duration"]), float(animation["fps"]), len(animation["tracks"]),
        flags, total_keys, mapping_hash, len(data))
    temporary = filepath + ".tmp"
    with open(temporary, "wb") as handle:
        handle.write(data)
    os.replace(temporary, filepath)
    return {"tracks": len(animation["tracks"]), "keyframes": total_keys, "size": len(data), "contentHash": f"{_fnv1a32(data):08x}", "validation": validation}


def _fnv1a32(data):
    value = 0x811C9DC5
    for byte in data:
        value ^= byte
        value = (value * 0x01000193) & 0xFFFFFFFF
    return value


def _build_target_mapping(base_document, raw_animations):
    node_names = _three_node_names(base_document)
    joint_indices = []
    for skin in base_document.get("skins", []):
        for node_index in skin.get("joints", []):
            if node_index not in joint_indices:
                joint_indices.append(node_index)
    bone_names = [node_names[index] for index in joint_indices]
    targets, used = [], set()
    for name in bone_names:
        if name not in used:
            targets.append({"name": name, "kind": "bone"})
            used.add(name)
    animated_names = sorted({track["target"] for animation in raw_animations for track in animation["tracks"]}, key=str.casefold)
    for name in animated_names:
        if name not in used:
            targets.append({"name": name, "kind": "object"})
            used.add(name)
    if len(targets) > 0xFFFF:
        raise RuntimeError("Binary format supports at most 65,535 animation targets.")
    target_ids = {entry["name"]: index for index, entry in enumerate(targets)}
    mapping_bytes = bytearray()
    for entry in targets:
        mapping_bytes.extend(entry["kind"].encode("utf-8"))
        mapping_bytes.append(0)
        mapping_bytes.extend(entry["name"].encode("utf-8"))
        mapping_bytes.append(0)
    return bone_names, targets, target_ids, _fnv1a32(mapping_bytes)


def _remove_previous_binary_files(output_dir, animation_dir):
    manifest_path = os.path.join(output_dir, MANIFEST_FILENAME)
    if not os.path.isfile(manifest_path):
        return
    try:
        with open(manifest_path, "r", encoding="utf-8") as handle:
            old_manifest = json.load(handle)
        animation_root = os.path.abspath(animation_dir)
        for metadata in old_manifest.get("animations", {}).values():
            candidate = os.path.abspath(os.path.join(output_dir, metadata.get("file", "")))
            if (candidate.lower().endswith(".anim") and
                    os.path.commonpath([candidate, animation_root]) == animation_root and
                    os.path.isfile(candidate)):
                os.remove(candidate)
    except (OSError, ValueError, TypeError, json.JSONDecodeError):
        print("[Binary Animation Export] Existing manifest cleanup skipped.")


def _safe_animation_filenames(animations):
    used, result = set(), []
    for animation in animations:
        base = _safe_filename(animation["name"])
        candidate, suffix = base, 2
        while candidate.casefold() in used:
            candidate = f"{base}_{suffix}"
            suffix += 1
        used.add(candidate.casefold())
        result.append((animation, candidate + ".anim"))
    return result


def export_character_and_animations():
    if not GLB_FILENAME.lower().endswith(".glb") or os.path.basename(GLB_FILENAME) != GLB_FILENAME:
        raise ValueError("GLB_FILENAME must be a filename ending in .glb.")
    if OUTPUT_DIRECTORY.startswith("//") and not bpy.data.filepath:
        raise RuntimeError("Save the .blend file first or configure an absolute OUTPUT_DIRECTORY.")
    if not 3 <= DECIMAL_PRECISION <= 9:
        raise ValueError("DECIMAL_PRECISION must be between 3 and 9.")
    if SAMPLING_FPS <= 0:
        raise ValueError("SAMPLING_FPS must be greater than zero.")
    if any(value < 0 for value in (POSITION_TOLERANCE, ROTATION_TOLERANCE_DEGREES, SCALE_TOLERANCE, MORPH_TOLERANCE)):
        raise ValueError("Animation tolerances cannot be negative.")

    output_dir = bpy.path.abspath(OUTPUT_DIRECTORY)
    animation_dir = os.path.join(output_dir, "animations")
    glb_path = os.path.join(output_dir, GLB_FILENAME)
    staging_path = os.path.join(output_dir, _STAGING_FILENAME)
    manifest_path = os.path.join(output_dir, MANIFEST_FILENAME)
    armature, meshes = _find_primary_armature()
    character_objects = _collect_character_objects(armature, meshes)
    actions = _find_character_actions(armature, meshes)
    wanted_names = {action.name for action in actions}
    scene_fps = bpy.context.scene.render.fps / bpy.context.scene.render.fps_base
    staging_frame_step = 1
    effective_fps = float(SAMPLING_FPS)
    os.makedirs(animation_dir, exist_ok=True)
    state = _snapshot_scene_state(character_objects)
    quarantine, quarantine_records = None, []
    generated_files = []
    _ensure_object_mode()

    try:
        _progress(2, f"Detected armature {armature.name} and {len(meshes)} skinned meshes")
        _export_glb(glb_path, character_objects, animations=False)
        base_document, _base_binary = _read_glb(glb_path)
        if base_document.get("animations"):
            raise RuntimeError("character.glb unexpectedly contains animations.")
        if not base_document.get("skins"):
            raise RuntimeError("character.glb contains no skin. Check Armature modifiers and vertex groups.")
        generated_files.append(glb_path)
        _progress(18, "Exported animation-free character GLB")

        raw_animations = []
        if actions:
            quarantine, quarantine_records = _quarantine_unsafe_fcurves()
            if quarantine_records:
                print(f"[Binary Animation Export] Temporarily skipped {len(quarantine_records)} unsupported F-curve(s); evaluated transforms remain sampled.")
            _progress(22, f"Sampling {len(actions)} evaluated Actions through Blender glTF")
            _export_glb(staging_path, character_objects, animations=True, frame_step=staging_frame_step)
            animation_document, animation_binary = _read_glb(staging_path)
            raw_animations = _extract_raw_animation_data(animation_document, animation_binary, wanted_names, scene_fps)
            raw_animations = _resample_raw_animations(raw_animations, effective_fps)
        exported_names = {animation["name"] for animation in raw_animations}
        missing = sorted(wanted_names - exported_names, key=str.casefold)
        if missing:
            raise RuntimeError("Blender did not emit these character Actions: " + ", ".join(missing))
        _progress(62, "Extracted evaluated glTF-space tracks")

        bone_names, targets, target_ids, mapping_hash = _build_target_mapping(base_document, raw_animations)
        optimized_animations = []
        for raw_animation in raw_animations:
            optimized_tracks = []
            removed_validation = {"position": 0.0, "quaternion": 0.0, "scale": 0.0, "morph": 0.0}
            for raw_track in raw_animation["tracks"]:
                optimized = _optimize_binary_track(raw_track)
                if optimized:
                    optimized_tracks.append(optimized)
                elif raw_track["rest"] is not None:
                    removed_validation[raw_track["property"]] = max(
                        removed_validation[raw_track["property"]],
                        max((_property_error(raw_track["property"], value, raw_track["rest"])
                             for value in raw_track["values"]), default=0.0),
                    )
            optimized_animations.append({
                "name": raw_animation["name"], "duration": raw_animation["duration"],
                "fps": raw_animation["fps"], "tracks": optimized_tracks,
                "original_tracks": len(raw_animation["tracks"]),
                "removed_validation": removed_validation,
                "original_keys": sum(len(track["times"]) for track in raw_animation["tracks"]),
            })

        _remove_previous_binary_files(output_dir, animation_dir)
        manifest_animations, reports = {}, []
        named = _safe_animation_filenames(optimized_animations)
        for index, (animation, filename) in enumerate(named):
            filepath = os.path.join(animation_dir, filename)
            encoded = _write_binary_animation(filepath, animation, target_ids, mapping_hash)
            generated_files.append(filepath)
            original_keys, optimized_keys = animation["original_keys"], encoded["keyframes"]
            reduction = 0.0 if original_keys == 0 else (1.0 - optimized_keys / original_keys) * 100.0
            errors = encoded["validation"]
            metadata = {
                "file": "animations/" + filename,
                "duration": round(animation["duration"], DECIMAL_PRECISION),
                "fps": round(animation["fps"], DECIMAL_PRECISION),
                "tracks": encoded["tracks"], "keyframes": optimized_keys, "size": encoded["size"],
                "contentHash": encoded["contentHash"],
                "validation": {
                    "originalSampledKeyframes": original_keys, "optimizedKeyframes": optimized_keys,
                    "reductionPercent": round(reduction, 2),
                    "maxPositionError": errors["position"],
                    "maxRotationErrorDegrees": math.degrees(errors["quaternion"]),
                    "maxScaleError": errors["scale"], "maxMorphError": errors["morph"],
                },
            }
            manifest_animations[animation["name"]] = metadata
            reports.append((animation["name"], metadata))
            _progress(65 + int(28 * (index + 1) / max(1, len(named))), f"Encoded {animation['name']}")

        manifest = {
            "version": _FORMAT_VERSION, "format": "T3AN", "character": GLB_FILENAME,
            "source": os.path.basename(bpy.data.filepath) if bpy.data.filepath else None,
            "mappingHash": mapping_hash, "skeleton": bone_names,
            "objects": [entry["name"] for entry in targets if entry["kind"] == "object"],
            "properties": {"position": 0, "quaternion": 1, "scale": 2, "morphTarget": 3},
            "animations": manifest_animations,
        }
        _atomic_write(manifest_path, json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
        generated_files.append(manifest_path)
        _progress(98, "Validated binary files and wrote manifest")

        print("\n" + "=" * 92)
        print("THREE.JS BINARY CHARACTER EXPORT COMPLETE")
        print("=" * 92)
        print(f"Character GLB: {glb_path}")
        print(f"Manifest: {manifest_path}")
        print(f"Armature: {armature.name} | Skeleton: {len(bone_names)} | Targets: {len(targets)}")
        print(f"Effective sampling FPS: {effective_fps:g} (scene {scene_fps:g}, exact time-grid resampling)")
        for name, metadata in reports:
            validation = metadata["validation"]
            print(f"  {name}: {metadata['tracks']} tracks | {validation['originalSampledKeyframes']} -> "
                  f"{metadata['keyframes']} keys ({validation['reductionPercent']:.2f}% reduction) | "
                  f"{_human_size(metadata['size'])} | max pos {validation['maxPositionError']:.7g}, "
                  f"rot {validation['maxRotationErrorDegrees']:.7g} deg, scale {validation['maxScaleError']:.7g}")
        print("Generated files:")
        for filepath in generated_files:
            print(f"  {filepath} — {_human_size(os.path.getsize(filepath))}")
        print("=" * 92)
        _progress(100, "Complete")
        return {
            "character_glb": glb_path, "manifest": manifest_path, "animations": manifest_animations,
            "tracks": sum(item["tracks"] for item in manifest_animations.values()),
            "keyframes": sum(item["keyframes"] for item in manifest_animations.values()),
            "files": generated_files,
        }
    finally:
        if quarantine:
            try:
                _restore_quarantined_fcurves(quarantine, quarantine_records)
            except Exception:
                print("[Binary Animation Export] ERROR restoring quarantined F-curves; copies remain in __TJS_EXPORT_QUARANTINE__.")
                traceback.print_exc()
        if os.path.isfile(staging_path):
            try:
                os.remove(staging_path)
            except OSError:
                pass
        _restore_scene_state(state)


if __name__ == "__main__":
    try:
        export_character_and_animations()
    except Exception:
        print("[Binary Animation Export] FAILED")
        traceback.print_exc()
        raise
