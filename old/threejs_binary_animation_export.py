def _node_rest_value(document, node_index, path):
    node = document["nodes"][node_index]
    if path == "translation":
        return node.get("translation", [0.0, 0.0, 0.0])
    if path == "rotation":
        return node.get("rotation", [0.0, 0.0, 0.0, 1.0])
    if path == "scale":
        return node.get("scale", [1.0, 1.0, 1.0])
    return None


def _three_node_names(document):
    """Mirror GLTFLoader/PropertyBinding node-name sanitizing and uniqueness."""
    result = {}
    used = {}
    for index, node in enumerate(document.get("nodes", [])):
        original = node.get("name") or f"node_{index}"
        sanitized = re.sub(r"\s", "_", original)
        sanitized = re.sub(r"[\[\]\.:/]", "", sanitized) or f"node_{index}"
        duplicate_index = used.get(sanitized, 0)
        used[sanitized] = duplicate_index + 1
        result[index] = (
            sanitized if duplicate_index == 0
            else f"{sanitized}_{duplicate_index}"
        )
    return result


def _quat_normalize(quaternion):
    length = math.sqrt(sum(value * value for value in quaternion))
    if length <= 1e-12:
        return [0.0, 0.0, 0.0, 1.0]
    return [value / length for value in quaternion]


def _quat_slerp(first, second, factor):
    first = _quat_normalize(first)
    second = _quat_normalize(second)
    dot = sum(a * b for a, b in zip(first, second))
    if dot < 0.0:
        second = [-value for value in second]
        dot = -dot
    dot = min(1.0, max(-1.0, dot))
    if dot > 0.9995:
        return _quat_normalize([
            a + factor * (b - a) for a, b in zip(first, second)
        ])
    angle = math.acos(dot)
    sine = math.sin(angle)
    left = math.sin((1.0 - factor) * angle) / sine
    right = math.sin(factor * angle) / sine
    return [left * a + right * b for a, b in zip(first, second)]


def _close_values(first, second, epsilon):
    return len(first) == len(second) and all(
        abs(a - b) <= epsilon for a, b in zip(first, second)
    )


def _interpolated_value(first, second, factor, property_name):
    if property_name == "quaternion":
        return _quat_slerp(first, second, factor)
    return [a + factor * (b - a) for a, b in zip(first, second)]


def _optimize_track(times, values, property_name, rest_value):
    if not times or len(times) != len(values):
        return None
    epsilon = 10.0 ** (-DECIMAL_PRECISION)

    if property_name == "quaternion":
        normalized = []
        for value in values:
            value = _quat_normalize(value)
            if normalized and sum(
                a * b for a, b in zip(normalized[-1], value)
            ) < 0.0:
                value = [-component for component in value]
            normalized.append(value)
        values = normalized

    if rest_value is not None and all(
        _close_values(value, rest_value, epsilon) for value in values
    ):
        return None

    if len(times) > 2:
        kept_indices = [0]
        for index in range(1, len(times) - 1):
            previous = kept_indices[-1]
            following = index + 1
            span = times[following] - times[previous]
            if abs(span) <= 1e-12:
                kept_indices.append(index)
                continue
            factor = (times[index] - times[previous]) / span
            predicted = _interpolated_value(
                values[previous], values[following], factor, property_name
            )
            if not _close_values(values[index], predicted, epsilon):
                kept_indices.append(index)
        kept_indices.append(len(times) - 1)
        times = [times[index] for index in kept_indices]
        values = [values[index] for index in kept_indices]

    rounded_times = [_round_float(value) for value in times]
    rounded_values = [
        [_round_float(component) for component in value]
        for value in values
    ]
    return rounded_times, rounded_values


def _round_float(value):
    rounded = round(float(value), DECIMAL_PRECISION)
    return 0.0 if abs(rounded) < 10.0 ** (-DECIMAL_PRECISION) else rounded


def _take_cubic_spline_values(rows):
    return [rows[index] for index in range(1, len(rows), 3)]


def _extract_standard_track(document, binary, channel, sampler, node_names):
    node_index = channel["target"]["node"]
    path = channel["target"]["path"]
    target_name = node_names[node_index]
    times = [row[0] for row in _read_accessor(
        document, binary, sampler["input"]
    )]
    values = _read_accessor(document, binary, sampler["output"])
    interpolation = sampler.get("interpolation", "LINEAR")
    if interpolation == "CUBICSPLINE":
        values = _take_cubic_spline_values(values)

    property_map = {
        "translation": "position",
        "rotation": "quaternion",
        "scale": "scale",
    }
    property_name = property_map[path]
    optimized = _optimize_track(
        times, values, property_name,
        _node_rest_value(document, node_index, path),
    )
    if not optimized:
        return None
    times, values = optimized
    return {
        "target": target_name,
        "property": property_name,
        "times": times,
        "values": [component for value in values for component in value],
        **({"interpolation": "discrete"}
           if interpolation == "STEP" else {}),
    }


def _extract_weight_tracks(document, binary, channel, sampler, node_names):
    node_index = channel["target"]["node"]
    node = document["nodes"][node_index]
    target_name = node_names[node_index]
    mesh = document["meshes"][node["mesh"]]
    target_names = mesh.get("extras", {}).get("targetNames", [])
    times = [row[0] for row in _read_accessor(
        document, binary, sampler["input"]
    )]
    rows = _read_accessor(document, binary, sampler["output"])
    flat = [component for row in rows for component in row]
    interpolation = sampler.get("interpolation", "LINEAR")

    divisor = len(times) * (3 if interpolation == "CUBICSPLINE" else 1)
    target_count = len(flat) // divisor if divisor else 0
    if target_count == 0:
        return []

    if interpolation == "CUBICSPLINE":
        sampled = []
        block = target_count * 3
        for index in range(len(times)):
            start = index * block + target_count
            sampled.append(flat[start:start + target_count])
    else:
        sampled = [
            flat[index * target_count:(index + 1) * target_count]
            for index in range(len(times))
        ]

    rest_weights = node.get("weights", mesh.get(
        "weights", [0.0] * target_count
    ))
    tracks = []
    for target_index in range(target_count):
        values = [[sample[target_index]] for sample in sampled]
        rest = [rest_weights[target_index]
                if target_index < len(rest_weights) else 0.0]
        optimized = _optimize_track(
            times, values,
            f"morphTargetInfluences[{target_index}]",
            rest,
        )
        if not optimized:
            continue
        track_times, track_values = optimized
        track = {
            "target": target_name,
            "property": f"morphTargetInfluences[{target_index}]",
            "times": track_times,
            "values": [value[0] for value in track_values],
        }
        if target_index < len(target_names):
            track["morphTarget"] = target_names[target_index]
        if interpolation == "STEP":
            track["interpolation"] = "discrete"
        tracks.append(track)
    return tracks


def _extract_animation_data(document, binary, wanted_names, effective_fps):
    grouped = {}
    node_names = _three_node_names(document)
    for animation_index, animation in enumerate(
        document.get("animations", [])
    ):
        name = animation.get("name") or f"Animation_{animation_index + 1}"
        if name not in wanted_names:
            continue
        entry = grouped.setdefault(name, {"name": name, "tracks": []})
        for channel in animation.get("channels", []):
            sampler = animation["samplers"][channel["sampler"]]
            path = channel.get("target", {}).get("path")
            if path in {"translation", "rotation", "scale"}:
                track = _extract_standard_track(
                    document, binary, channel, sampler, node_names
                )
                if track:
                    entry["tracks"].append(track)
            elif path == "weights":
                entry["tracks"].extend(_extract_weight_tracks(
                    document, binary, channel, sampler, node_names
                ))

    result = []
    for name in sorted(grouped, key=str.casefold):
        entry = grouped[name]
        duration = max(
            (max(track["times"]) for track in entry["tracks"]
             if track["times"]),
            default=0.0,
        )
        entry["duration"] = _round_float(duration)
        entry["fps"] = _round_float(effective_fps)
        entry["tracks"].sort(
            key=lambda track: (track["target"], track["property"])
        )
        result.append(entry)
    return result


